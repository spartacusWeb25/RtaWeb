-- ============================================================================
--  TABELA OFICIAL CBO (Classificação Brasileira de Ocupações - MTE 2002)
--  Estrutura genérica para armazenar os ~3.300 CBOs oficiais do Ministério
--  do Trabalho e Emprego. Usada como FONTE PRIORITÁRIA para autocompletar
--  o combo de CBO na tela de Plano de Cargos (app cargos) e demais módulos.
-- ============================================================================

DROP TABLE IF EXISTS public.cbo_oficial CASCADE;

CREATE TABLE public.cbo_oficial (
  cbo_codi     varchar(7)   NOT NULL,   -- Código CBO 6 ou 7 dígitos (ex: '252510')
  cbo_desc     varchar(250) NOT NULL,   -- Descrição oficial da ocupação (ex: 'Analista de sistemas')
  cbo_familia  varchar(50),             -- Família ocupacional opcional (ex: 'Tecnologia da Informação')
  _log_data    date,
  _log_time    time,
  CONSTRAINT pk_cbo_oficial PRIMARY KEY (cbo_codi)
);

CREATE INDEX idx_cbo_oficial_desc ON public.cbo_oficial (upper(cbo_desc::text));

ALTER TABLE public.cbo_oficial OWNER TO postgres;

